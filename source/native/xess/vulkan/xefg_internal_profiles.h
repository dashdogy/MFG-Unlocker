// fg95prov.1: the libxess_fg images whose internal frame-generation entry points we profiled (xefg_internal.h), each
// pinned by its PE identity and the first 32 bytes at every entry. API-free so the CPU tests read the same table.
//
// fg78 = XeFG 1.3.1.78 (XeSS SDK 3.0.2), libxess_fg EC5E0C65.
// fg95 = XeFG 1.3.4.95, libxess_fg 752B1491 (22,866,056 B).
// Both from our own reverse engineering; the validators' strings name the entries (xefg_internal.h). In fg95 the
// entries, the validators, the resource converter and the swap chain's own callers decompile the same as fg78 apart
// from addresses; Create only allocates a larger implementation (0x130 -> 0x138 bytes, XeFG's own). So InitParams
// (0x50) and ExecuteParams (0x260) are unchanged; only the RVAs move.
#include <cstddef>
#include <cstdint>

