// The profile whose PE identity matches all three fields, else null. A match pins the RVAs; Resolve still checks
// every entry's bytes in the loaded image.
constexpr const Profile* FindProfile(uint32_t timeDateStamp, uint32_t sizeOfImage, uint32_t checkSum) noexcept
{
    for (const Profile& profile : kProfiles)
        if (profile.timeDateStamp == timeDateStamp && profile.sizeOfImage == sizeOfImage && profile.checkSum == checkSum)
            return &profile;
    return nullptr;
}
