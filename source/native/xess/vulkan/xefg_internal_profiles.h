struct Entry
{
    const char* name;
    uint32_t rva;
    uint8_t bytes[32];   // the prologue and the stack-cookie load (mov rax,[rip+disp32] -> securityCookie)
};

enum EntryIndex : size_t { kCreateContext, kInit, kExecute, kDestroy, kEntryCount };

struct Profile
{
    const char* family;          // host_unlock's family name
    const char* version;         // XeFG's file version
    uint32_t timeDateStamp;      // IMAGE_FILE_HEADER.TimeDateStamp
    uint32_t sizeOfImage;        // OptionalHeader.SizeOfImage
    uint32_t checkSum;           // OptionalHeader.CheckSum
    uint32_t securityCookie;     // RVA of __security_cookie, which every entry's cookie load reads (witness)
    Entry entries[kEntryCount];  // in EntryIndex order
};

