struct Patch { uint32_t rva; std::array<uint8_t,8> before,after; };
// Gates: every renderer read of the LSS capability byte (build 25575366: 0x4077e5c) is accounted for:
// the NVAPI pipeline-option requests (0x1ec4f8f, 0x1ed5d74) stay closed; the
// rest open the hair features this fallback supports, together. A partial set
// dispatched a never-registered raygen and an unbuilt RTAO-hair pipeline
// (SKEDCHECK16_CTA_THREAD_DIMENSION_ZERO, device hung).
struct Entry { uint32_t rva; std::array<uint8_t,16> before; };
// A hair operation's call: the return address our hook accepts, and the
// called entry it must decode to.
struct CallSite { uint32_t ret,target; };
// Static REDengine config variables (vtable, group, name, flags, value pointer,
// default, value). The renderer's path-traced-hair predicate needs
// Rendering/RT/PathTracer PTEnable and PTHairQualityMode > 0. `reader` is that
// predicate's compare of the value.
// The game's hair owner object (hair builder argument): the offsets of its
// scratch, BLAS, LSS position and index buffer pointers, and its readable size.
struct HairOwner { uint32_t scratch,blas,positions,indices,size; };
struct ConfigVar { uint32_t object,value;const char* group;const char* name;uint64_t flags;uint32_t reader;uint8_t opcode; };
// Everything DOTS reads, hooks or patches in one witcher3.exe build. A build
// is admitted only by its exact executable size and SHA-256; ValidateMapped
// then checks every entry, gate, call site and layout in the loaded image.
struct GameProfile {
    const char* label;
    uint64_t exeSize;const char* exeHash;
    uint32_t minImageSize;
    std::span<const Patch> gates;        // the logical LSS getter is last
    std::array<Entry,5> entries;         // hair builder, prebuild, build, instance copy, NVAPI caps
    uint32_t hairWriterRva;std::array<uint8_t,34> hairWriter;
    uint32_t ordinaryWriterRva;std::array<uint8_t,18> ordinaryWriter;
    std::array<uint32_t,2> deviceReturns;uint32_t deviceImport; // D3D12CreateDevice calls of the renderer
    std::array<CallSite,3> hairCalls;    // prebuild, build, instance copy
    ConfigVar ptEnable,ptHairQuality;
    std::array<uint32_t,4> shaders;      // ClosestHitHair (two copies), PTHairPrepassRGS (two copies)
    std::array<uint32_t,2> shaderSizes;  // ClosestHitHair, PTHairPrepassRGS
    HairOwner owner;
};
