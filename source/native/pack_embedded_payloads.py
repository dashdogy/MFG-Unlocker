"""Pack one generated RCDATA list into a single LZMA-compressed resource (V1.7.1 slim.1).

The input is a generated .rc whose payload lines read `<id> RCDATA "<file>"`. The files are joined in that
order and compressed as one .lzma stream, which LZMA SDK's LzmaDec (third_party/lzma) decodes in
embedded_payload.cpp. The outputs replace the input .rc in the build: <name>.packed.rc holds the one packed
resource, and <name>.packed.h describes the group and where each old id's bytes sit in it, so the loaders keep
asking by the old ids. embedded_payload::Find checks the decoded group's SHA-256 before it returns any bytes.
"""
from pathlib import Path
import argparse
import hashlib
import json
import lzma
import re

SLOTS = 8  # embedded_payload::kSlots
ROW = re.compile(r'^(\d+)\s+RCDATA\s+"([^"]+)"$')

parser = argparse.ArgumentParser()
parser.add_argument("--rc", type=Path, required=True, help='generated .rc listing <id> RCDATA "<file>"')
parser.add_argument("--name", required=True, help="C++ name of the group, e.g. xvk_programs")
parser.add_argument("--slot", type=int, required=True, help="embedded_payload slot, one per group in a module")
parser.add_argument("--resource", type=int, required=True, help="RCDATA id of the packed resource")
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()

if not re.fullmatch(r"[a-z][a-z0-9_]*", args.name):
    raise SystemExit(f"Invalid group name {args.name!r}")
if not 0 <= args.slot < SLOTS or not 1 <= args.resource <= 0xFFFF:
    raise SystemExit(f"Slot {args.slot} or resource {args.resource} out of range")

items = []
for line in args.rc.read_text(encoding="utf-8").splitlines():
    line = line.strip()
    if not line or line.startswith("#include") or line.startswith("LANGUAGE"):
        continue
    match = ROW.match(line)
    if not match:
        raise SystemExit(f"{args.rc}: unexpected line {line!r}")
    items.append((int(match.group(1)), Path(match.group(2))))
ids = [resource for resource, _ in items]
if not items or len(set(ids)) != len(ids) or args.resource in ids:
    raise SystemExit(f"{args.rc}: no payloads, a repeated id, or the packed id {args.resource} already used")

raw = bytearray()
table = []
for resource, path in items:
    data = path.read_bytes()
    table.append((resource, len(raw), len(data)))
    raw += data
if not raw or len(raw) >= 1 << 31:
    raise SystemExit(f"{args.rc}: payload size {len(raw)} out of range")
raw = bytes(raw)
raw_sha256 = hashlib.sha256(raw).hexdigest()

# One-call LzmaDecode writes straight into the output buffer, so the dictionary costs the decoder nothing.
dict_size = min(max(1 << 16, 1 << (len(raw) - 1).bit_length()), 1 << 26)
settings = {"raw_sha256": raw_sha256, "raw_bytes": len(raw), "format": "alone", "preset": "9e", "dict_size": dict_size}
args.output.mkdir(parents=True, exist_ok=True)
blob = args.output / f"{args.name}.lzma"
stamp = args.output / f"{args.name}.lzma.json"
# Compressing the larger groups takes seconds; keep the stream while its input and settings are unchanged.
packed = None
if blob.is_file() and stamp.is_file():
    try:
        previous = json.loads(stamp.read_text(encoding="utf-8"))
    except ValueError:
        previous = {}  # a damaged stamp only means the stream is compressed again
    candidate = blob.read_bytes()
    if previous.get("settings") == settings and previous.get("packed_sha256") == hashlib.sha256(candidate).hexdigest():
        packed = candidate
if packed is None:
    packed = lzma.compress(raw, format=lzma.FORMAT_ALONE,
                           filters=[{"id": lzma.FILTER_LZMA1, "preset": 9 | lzma.PRESET_EXTREME, "dict_size": dict_size}])
    blob.write_bytes(packed)
    stamp.write_text(json.dumps({"settings": settings, "packed_sha256": hashlib.sha256(packed).hexdigest()}, indent=1) + "\n",
                     encoding="utf-8")
# .lzma header: 5 property bytes, then the 8-byte size, which liblzma writes as unknown (the stream ends with a marker).
if lzma.decompress(packed, format=lzma.FORMAT_ALONE) != raw or len(packed) <= 13 or packed[5:13] != b"\xff" * 8:
    raise SystemExit(f"{blob}: does not decode to its input")

rc = ["#include <windows.h>", "LANGUAGE LANG_NEUTRAL, SUBLANG_NEUTRAL",
      f'{args.resource} RCDATA "{blob.resolve().as_posix()}"']
header = ["#pragma once", f"// Generated by pack_embedded_payloads.py from {args.rc.name}; do not edit.",
          f"// {len(table)} payloads, {len(raw)} bytes, packed to {len(packed)} bytes.",
          '#include "embedded_payload.h"', "namespace embedded_payload::packed {",
          f'inline constexpr Group {args.name}{{{args.slot}u, {args.resource}u, {len(packed)}u, {len(raw)}u, "{raw_sha256}", '
          f'"{args.name}"}};',
          f"inline constexpr Item {args.name}_items[] = {{"]
header += [f"    {{{resource}u, {offset}u, {size}u}}," for resource, offset, size in table]
header += ["};", "}"]
for name, lines in ((f"{args.name}.packed.rc", rc), (f"{args.name}.packed.h", header)):
    text = "\n".join(lines) + "\n"
    target = args.output / name
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        target.write_text(text, encoding="utf-8")
print(f"Packed {len(table)} {args.name} payloads: {len(raw)} -> {len(packed)} bytes (resource {args.resource})")
