"""Describe one generated RCDATA list as a payload group (V1.7.1 slim.1; uncompressed since V1.7.2 nolzma.1).

The input is a generated .rc whose payload lines read `<id> RCDATA "<file>"`. Every payload stays its own uncompressed
resource at its own id, as up to V1.7.0. V1.7.1 slim.1 joined each group into one LZMA stream that the module decoded at
run time; V1.7.2 nolzma.1 dropped that and its decoder, because a compressed blob unpacked at run time is what a packed
loader looks like to antivirus scanners (V1.7.1 was quarantined as Trojan:Win32/Posilod.EB!cl).

The outputs replace the input .rc in the build: <name>.packed.rc lists the payloads, and <name>.packed.h describes the
group (each id, its offset and size in the joined bytes, and the SHA-256 of the payloads joined in that order), which
embedded_payload::Find checks before it returns any bytes. The file names are slim.1's, so loaders and tools keep them.
"""
from pathlib import Path
import argparse
import hashlib
import re

SLOTS = 8  # embedded_payload::kSlots
ROW = re.compile(r'^(\d+)\s+RCDATA\s+"([^"]+)"$')

parser = argparse.ArgumentParser()
parser.add_argument("--rc", type=Path, required=True, help='generated .rc listing <id> RCDATA "<file>"')
parser.add_argument("--name", required=True, help="C++ name of the group, e.g. xvk_programs")
parser.add_argument("--slot", type=int, required=True, help="embedded_payload slot, one per group in a module")
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()

if not re.fullmatch(r"[a-z][a-z0-9_]*", args.name):
    raise SystemExit(f"Invalid group name {args.name!r}")
if not 0 <= args.slot < SLOTS:
    raise SystemExit(f"Slot {args.slot} out of range")

items = []
for line in args.rc.read_text(encoding="utf-8").splitlines():
    line = line.strip()
    if not line or line.startswith("#include") or line.startswith("LANGUAGE"):
        continue
    match = ROW.match(line)
    if not match:
        raise SystemExit(f"{args.rc}: unexpected line {line!r}")
    items.append((int(match.group(1)), Path(match.group(2))))
ids = [resource for resource, _ in items]
if not items or len(set(ids)) != len(ids) or not all(1 <= resource <= 0xFFFF for resource in ids):
    raise SystemExit(f"{args.rc}: no payloads, a repeated id, or an id out of range")

digest = hashlib.sha256()
table = []
joined = 0
for resource, path in items:
    data = path.read_bytes()
    if not data:
        raise SystemExit(f"{args.rc}: payload {resource} ({path}) is empty")
    table.append((resource, joined, len(data)))
    digest.update(data)
    joined += len(data)
if joined >= 1 << 31:
    raise SystemExit(f"{args.rc}: payload size {joined} out of range")
raw_sha256 = digest.hexdigest()

args.output.mkdir(parents=True, exist_ok=True)
# slim.1's stream and its stamp from an earlier configure of this tree: nothing reads them now, so no gate or resource
# script can pick up a stale one.
for stale in (args.output / f"{args.name}.lzma", args.output / f"{args.name}.lzma.json"):
    stale.unlink(missing_ok=True)

rc = ["#include <windows.h>", "LANGUAGE LANG_NEUTRAL, SUBLANG_NEUTRAL"]
rc += [f'{resource} RCDATA "{path.resolve().as_posix()}"' for resource, path in items]
header = ["#pragma once", f"// Generated by pack_embedded_payloads.py from {args.rc.name}; do not edit.",
          f"// {len(table)} payloads, {joined} bytes, each its own uncompressed RCDATA resource.",
          '#include "embedded_payload.h"', "namespace embedded_payload::packed {",
          f'inline constexpr Group {args.name}{{{args.slot}u, {joined}u, "{raw_sha256}", "{args.name}"}};',
          f"inline constexpr Item {args.name}_items[] = {{"]
header += [f"    {{{resource}u, {offset}u, {size}u}}," for resource, offset, size in table]
header += ["};", "}"]
for name, lines in ((f"{args.name}.packed.rc", rc), (f"{args.name}.packed.h", header)):
    text = "\n".join(lines) + "\n"
    target = args.output / name
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        target.write_text(text, encoding="utf-8")
print(f"Listed {len(table)} {args.name} payloads: {joined} bytes, uncompressed (ids {min(ids)}-{max(ids)})")
