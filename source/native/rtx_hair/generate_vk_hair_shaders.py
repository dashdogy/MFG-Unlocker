"""vkhair.3: compile universal hair's Vulkan compute shaders (rtx_hair/vk_dots_converter.comp and
rtx_hair/vk_instance_patch.comp, both including rtx_hair/vk_common.glsl) into rtxhair_vk_shaders.h.

Built with the module's pinned glslangValidator (Vulkan SDK 1.2.176.1); each shader's SPIR-V is pinned below.

    python generate_vk_hair_shaders.py --glslang <glslangValidator.exe> --source <source/native> --output <dir>
"""
from pathlib import Path
import argparse
import hashlib
import struct
import subprocess

GLSLANG_SHA256 = "8F0838D3FD981D4086D81675C4CFA4381691AEAFC3651D12D62F61EF0CEBB33E"
SHADERS = [  # (file, array name, extra glslangValidator arguments, pinned SPIR-V SHA-256 or None)
    ("vk_dots_converter.comp", "kConverter", [], "FE9069F8D5CEF0011E236B29701E3987EBD8EDE794DE0F1FC7757F08017F384A"),
    # hairmem.1: [RtxHair] Ribbons=2 (two ribbons per segment), pinned from 1.7.1-hairmem.1's build (1.7.1.168); the
    # default converter above kept its pin, which proves the -DRIBBONS variant left it unchanged.
    ("vk_dots_converter.comp", "kConverterTwoRibbons", ["-DRIBBONS=2"], "2E66A8A414D46A6CA15A0EB0C5418C6B291F218E14E503375064B93D57520FAD"),
    ("vk_instance_patch.comp", "kInstancePatch", [], "2ABFCFF08FC01D2B5B62814D2E7FD7C54626403CDD2E3194E449C3866585BB1D"),
]

parser = argparse.ArgumentParser()
parser.add_argument("--glslang", type=Path, required=True)
parser.add_argument("--source", type=Path, required=True)
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()

if hashlib.sha256(args.glslang.read_bytes()).hexdigest().upper() != GLSLANG_SHA256:
    raise SystemExit("Expected glslangValidator from Vulkan SDK 1.2.176.1")
args.output.mkdir(parents=True, exist_ok=True)
folder = args.source / "rtx_hair"
header = ["#pragma once", "// Generated by rtx_hair/generate_vk_hair_shaders.py. Do not edit.", "#include <cstdint>",
          "namespace rtx_hair::vk_shaders {"]
for name, array, extra, pinned in SHADERS:
    spv = args.output / (array + ".spv")
    subprocess.run([str(args.glslang), "-V", *extra, "-I" + str(folder), "-o", str(spv), str(folder / name)], check=True,
                   stdout=subprocess.DEVNULL)
    raw = spv.read_bytes()
    digest = hashlib.sha256(raw).hexdigest().upper()
    if pinned is not None and digest != pinned:
        raise SystemExit(f"{name} {' '.join(extra)} output drifted: {digest}")
    words = struct.unpack(f"<{len(raw) // 4}I", raw)
    header.append(f"inline constexpr uint32_t {array}[] = {{")
    for at in range(0, len(words), 8):
        header.append("    " + ",".join(f"0x{word:08x}u" for word in words[at:at + 8]) + ",")
    header.append("};")
    print(f"{name} {' '.join(extra)}: {array} {digest} ({len(raw)} bytes){'' if pinned else ' (not pinned)'}")
header.append("}")
text = "\n".join(header) + "\n"
target_path = args.output / "rtxhair_vk_shaders.h"
if not target_path.exists() or target_path.read_text(encoding="ascii") != text:
    target_path.write_text(text, encoding="ascii")
