"""vkhair.1: writes spirv_grammar.inl, the operand table spirv_module.cpp walks SPIR-V with.

Input: SPIR-V's machine-readable grammar, spirv.core.grammar.json, from the pinned Vulkan SDK
1.4.363.0 (Include/spirv/unified1). Only what an operand walker needs is kept: per opcode whether
it has a result type and a result <id>, and each operand's kind (an <id>, a literal word, a string,
a context-dependent number, a pair, or an enum whose values carry further operands) and quantifier.

    python spirv_grammar.py <spirv.core.grammar.json> <spirv_grammar.inl>
"""
import json
import sys

ID, LITERAL, STRING, CONTEXT_NUMBER, PAIR_LITERAL_ID, PAIR_ID_LITERAL, PAIR_ID_ID, VALUE_ENUM, BIT_ENUM = range(1, 10)
QUANTIFIERS = {'': 0, '?': 1, '*': 2}


def main(source, target):
    with open(source, encoding='utf-8') as f:
        grammar = json.load(f)
    kinds = {k['kind']: k for k in grammar['operand_kinds']}
    tables = {}  # enum kind with parameterized values -> table index
    for k in grammar['operand_kinds']:
        if k['category'] in ('ValueEnum', 'BitEnum') and any(e.get('parameters') for e in k['enumerants']):
            tables[k['kind']] = len(tables)

    def code(kind):
        if kind in ('IdRef', 'IdScope', 'IdMemorySemantics', 'IdResultType', 'IdResult'):
            return ID, 0
        info = kinds[kind]
        category = info['category']
        if category == 'Id':
            return ID, 0
        if category == 'Literal':
            if kind == 'LiteralString':
                return STRING, 0
            if kind == 'LiteralContextDependentNumber':
                return CONTEXT_NUMBER, 0
            return LITERAL, 0
        if category == 'Composite':
            return {'PairLiteralIntegerIdRef': PAIR_LITERAL_ID, 'PairIdRefLiteralInteger': PAIR_ID_LITERAL,
                    'PairIdRefIdRef': PAIR_ID_ID}[kind], 0
        if kind in tables:
            return (VALUE_ENUM if category == 'ValueEnum' else BIT_ENUM), tables[kind]
        return LITERAL, 0

    operands = []  # (kind, quantifier, table)
    instructions = {}
    for ins in grammar['instructions']:
        opcode = ins['opcode']
        if opcode in instructions:
            continue
        ops = ins.get('operands', [])
        has_type = bool(ops) and ops[0]['kind'] == 'IdResultType'
        rest = ops[1:] if has_type else ops
        has_result = bool(rest) and rest[0]['kind'] == 'IdResult'
        rest = rest[1:] if has_result else rest
        first = len(operands)
        for o in rest:
            kind, table = code(o['kind'])
            operands.append((kind, QUANTIFIERS[o.get('quantifier', '')], table))
        instructions[opcode] = (ins['opname'], has_type, has_result, first, len(operands) - first)

    parameters = []  # (table, value, first, count)
    for name, table in sorted(tables.items(), key=lambda item: item[1]):
        seen = set()
        for e in kinds[name]['enumerants']:
            value = e['value']
            value = int(value, 16) if isinstance(value, str) else value
            if value in seen or not e.get('parameters'):
                continue
            seen.add(value)
            first = len(operands)
            for p in e['parameters']:
                kind, sub = code(p['kind'])
                operands.append((kind, QUANTIFIERS[p.get('quantifier', '')], sub))
            parameters.append((table, value, first, len(operands) - first))
    parameters.sort()

    version = f"{grammar['major_version']}.{grammar['minor_version']} revision {grammar['revision']}"
    lines = [
        '// Generated by spirv_grammar.py from spirv.core.grammar.json (SPIR-V ' + version + ',',
        '// Vulkan SDK 1.4.363.0). Do not edit. The grammar is Copyright (c) 2014-2024 The Khronos Group Inc.',
        '// and is distributed under the MIT-style Khronos licence in its header; this table keeps only opcode',
        '// numbers and operand kinds from it.',
        '// clang-format off',
        f'inline constexpr uint32_t kGrammarVersion = 0x{grammar["major_version"]:02x}{grammar["minor_version"]:02x}{grammar["revision"]:04x}u;',
        '// Operand: {kind, quantifier, enum table}. Kinds: 1 id, 2 literal word, 3 string, 4 context-dependent',
        '// number, 5 literal-id pair, 6 id-literal pair, 7 id-id pair, 8 value enum with operands, 9 bit enum',
        '// with operands. Quantifiers: 0 one, 1 optional, 2 any number.',
        'inline constexpr GrammarOperand kGrammarOperands[] = {',
    ]
    row = []
    for kind, quantifier, table in operands:
        row.append(f'{{{kind},{quantifier},{table}}}')
        if len(row) == 12:
            lines.append('    ' + ','.join(row) + ',')
            row = []
    if row:
        lines.append('    ' + ','.join(row) + ',')
    lines.append('};')
    lines.append('// Instruction: {opcode, has result type, has result, first operand, operand count}, by opcode.')
    lines.append('inline constexpr GrammarInstruction kGrammarInstructions[] = {')
    for opcode in sorted(instructions):
        name, has_type, has_result, first, count = instructions[opcode]
        lines.append(f'    {{{opcode},{int(has_type)},{int(has_result)},{first},{count}}}, // {name}')
    lines.append('};')
    lines.append('// Enum values with operands: {table, value, first operand, operand count}, by table and value.')
    lines.append('inline constexpr GrammarEnumParameters kGrammarEnumParameters[] = {')
    for table, value, first, count in parameters:
        lines.append(f'    {{{table},0x{value:x}u,{first},{count}}},')
    lines.append('};')
    lines.append('// clang-format on')
    with open(target, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(instructions)} instructions, {len(operands)} operands, {len(parameters)} enum values with operands')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
