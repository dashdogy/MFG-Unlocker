"""Fixtures for the payload store tests (V1.7.1 slim.1; uncompressed payloads since V1.7.2 nolzma.1).

  payloads  three payload files and fixtures.rc listing them (ids 9001-9003), for pack_embedded_payloads.py
  damage    damaged copies of the group as their own resources: flipped (9011-9013, words.bin with one byte changed,
            same size) and truncated (9021-9023, words.bin without its last 64 bytes); damaged.rc lists them and
            damaged.h holds their tables (the good group's offsets and sizes) and the payload files the test compares
            against
"""
from pathlib import Path
import argparse
import hashlib

parser = argparse.ArgumentParser()
parser.add_argument("mode", choices=("payloads", "damage"))
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()
out = args.output
out.mkdir(parents=True, exist_ok=True)
FILES = [(9001, "noise.bin"), (9002, "words.bin"), (9003, "tiny.bin")]


def write_if_changed(path, data):
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def posix(name):
    return (out / name).resolve().as_posix()


if args.mode == "payloads":
    noise = b"".join(hashlib.sha256(i.to_bytes(4, "little")).digest() for i in range(2048))  # 64 KiB
    words = b"".join((0x07230203 + (i % 97)).to_bytes(4, "little") for i in range(50000))  # 200 KB
    for (resource, name), data in zip(FILES, (noise, words, b"\x01\x02\x03")):
        write_if_changed(out / name, data)
    rc = "".join(f'{resource} RCDATA "{posix(name)}"\n' for resource, name in FILES)
    write_if_changed(out / "fixtures.rc", rc.encode("ascii"))
else:
    sizes = [(out / name).stat().st_size for _, name in FILES]
    offsets = [sum(sizes[:i]) for i in range(len(sizes))]
    words = (out / "words.bin").read_bytes()
    flipped = bytearray(words)
    flipped[len(flipped) // 2] ^= 0x5A
    write_if_changed(out / "words_flipped.bin", bytes(flipped))
    write_if_changed(out / "words_truncated.bin", words[:-64])
    damaged = {"kFlippedItems": (9011, ["noise.bin", "words_flipped.bin", "tiny.bin"]),
               "kTruncatedItems": (9021, ["noise.bin", "words_truncated.bin", "tiny.bin"])}
    rc = ""
    header = ["#pragma once", "// Generated by make_fixtures.py damage; do not edit.", '#include "embedded_payload.h"',
              "#include <cstdint>"]
    for table, (first, names) in damaged.items():
        rc += "".join(f'{first + i} RCDATA "{posix(name)}"\n' for i, name in enumerate(names))
        header.append(f"inline constexpr embedded_payload::Item {table}[] = {{")
        header += [f"    {{{first + i}u, {offsets[i]}u, {sizes[i]}u}}," for i in range(len(names))]
        header.append("};")
    write_if_changed(out / "damaged.rc", rc.encode("ascii"))
    header += ["struct FixtureFile { uint32_t id; const char* path; };", "inline constexpr FixtureFile kFixtureFiles[] = {"]
    header += [f'    {{{resource}u, "{posix(name)}"}},' for resource, name in FILES]
    header += ["};"]
    write_if_changed(out / "damaged.h", ("\n".join(header) + "\n").encode("ascii"))
print(f"make_fixtures.py {args.mode}: {out}")
