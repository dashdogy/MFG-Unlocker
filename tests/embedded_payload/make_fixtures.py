"""Fixtures for the packed payload store tests (V1.7.1 slim.1).

  payloads  three payload files and fixtures.rc listing them (ids 9001-9003), for pack_embedded_payloads.py
  damage    from the packed fixtures.lzma: flipped.lzma (one byte changed mid-stream, proven not to decode to the
            input), truncated.lzma (the stream's last 64 bytes gone), damaged.rc (3951, 3952) and damaged.h (their
            sizes and the payload files the test compares against)
"""
from pathlib import Path
import argparse
import hashlib
import lzma

parser = argparse.ArgumentParser()
parser.add_argument("mode", choices=("payloads", "damage"))
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()
out = args.output
out.mkdir(parents=True, exist_ok=True)
FILES = [(9001, "noise.bin"), (9002, "words.bin"), (9003, "tiny.bin")]


def write_if_changed(path, data):
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


if args.mode == "payloads":
    noise = b"".join(hashlib.sha256(i.to_bytes(4, "little")).digest() for i in range(2048))  # 64 KiB, incompressible
    words = b"".join((0x07230203 + (i % 97)).to_bytes(4, "little") for i in range(50000))  # 200 KB, compressible
    for (resource, name), data in zip(FILES, (noise, words, b"\x01\x02\x03")):
        write_if_changed(out / name, data)
    rc = "".join(f'{resource} RCDATA "{(out / name).resolve().as_posix()}"\n' for resource, name in FILES)
    write_if_changed(out / "fixtures.rc", rc.encode("ascii"))
else:
    packed = (out / "fixtures.lzma").read_bytes()
    raw = lzma.decompress(packed, format=lzma.FORMAT_ALONE)
    flipped = bytearray(packed)
    at = len(packed) // 2
    while True:
        flipped[at] ^= 0x5A
        try:
            if lzma.decompress(bytes(flipped), format=lzma.FORMAT_ALONE) != raw:
                break
        except lzma.LZMAError:
            break
        flipped[at] ^= 0x5A
        at += 1
    truncated = packed[:-64]
    write_if_changed(out / "flipped.lzma", bytes(flipped))
    write_if_changed(out / "truncated.lzma", truncated)
    rc = (f'3951 RCDATA "{(out / "flipped.lzma").resolve().as_posix()}"\n'
          f'3952 RCDATA "{(out / "truncated.lzma").resolve().as_posix()}"\n')
    write_if_changed(out / "damaged.rc", rc.encode("ascii"))
    header = ["#pragma once", "// Generated by make_fixtures.py damage; do not edit.", "#include <cstdint>",
              f"inline constexpr uint32_t kFlippedBytes = {len(flipped)}u;",
              f"inline constexpr uint32_t kTruncatedBytes = {len(truncated)}u;",
              "struct FixtureFile { uint32_t id; const char* path; };",
              "inline constexpr FixtureFile kFixtureFiles[] = {"]
    header += [f'    {{{resource}u, "{(out / name).resolve().as_posix()}"}},' for resource, name in FILES]
    header += ["};"]
    write_if_changed(out / "damaged.h", ("\n".join(header) + "\n").encode("ascii"))
print(f"make_fixtures.py {args.mode}: {out}")
